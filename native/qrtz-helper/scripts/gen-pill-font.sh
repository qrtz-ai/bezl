#!/bin/bash
# Regenerates Sources/QrtzEcho/PillFont.swift from the renderer's bundled font, so the native echo pill draws
# with the same file (Core Text reads WOFF2 directly). PillTests fails if the two drift apart.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=../../packages/ui/src/fonts/GeistPixel-Square.woff2
{
  echo "// Generated by scripts/gen-pill-font.sh from packages/ui/src/fonts/GeistPixel-Square.woff2 (Geist Pixel Square,"
  echo "// Vercel geist 1.8.1, OFL-1.1: packages/ui/src/fonts/OFL-GeistPixel.txt). Do not edit."
  echo "import Foundation"
  echo ""
  echo "public enum PillFont {"
  echo "    public static let family = \"Geist Pixel Square\""
  echo "    /// PostScript name: unambiguous for NSFont(name:) even if other Geist Pixel faces are installed."
  echo "    public static let postScriptName = \"GeistPixel-Square\""
  echo "    public static var woff2: Data { Data(base64Encoded: base64)! }"
  printf '    static let base64 = "%s"\n' "$(base64 < "$SRC" | tr -d '\n')"
  echo "}"
} > Sources/QrtzEcho/PillFont.swift
