import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { z } from 'zod';
import {
  ConfigSchema,
  ErrorCode,
  HELPER_PROTOCOL_VERSION,
  HelperToHost,
  HostToHelper,
  IpcEnvelope,
  IpcResult,
  PROTOCOL_VERSION,
  SPEECH_LANGUAGES,
  SPEECH_LIMITS,
  SPEECH_PROTOCOL_VERSION,
  HostToSpeech,
  SpeechToHost,
  defaultConfig,
  eventContract,
  ipcContract,
  type EventDef,
} from '@qrtz/core';
import {
  eventSamples,
  idleResponses,
  ipcSamples,
} from '@qrtz/core/ipc/samples';
import { manifests } from './manifests';

/**
 * zod stays the single source of truth for the IPC contract and the helper protocol during the
 * Electron → Tauri dual run (see docs/tauri-migration.md). This test renders both to JSON Schema
 * under contracts/, which the Rust crates embed (crates/qrtz-ipc, crates/qrtz-helper-bridge).
 * If it fails, a zod schema changed: run `bun run gen:contracts` and commit the result.
 */
const root = path.resolve(__dirname, '../../../..');
const UPDATE = process.env.QRTZ_UPDATE_CONTRACTS === '1';

const schema = (t: z.ZodType, io: 'input' | 'output') => {
  const { $schema: _drop, ...rest } = z.toJSONSchema(t, {
    io,
    unrepresentable: 'throw',
  }) as Record<string, unknown>;
  return rest;
};

/** Requests: void = payload must be absent/null; optional = absent is valid (zod accepts undefined). */
const requestSpec = (t: z.ZodType) => {
  if (t instanceof z.ZodVoid) return { void: true };
  return {
    optional: t.safeParse(undefined).success,
    schema: schema(t, 'input'),
  };
};

export function renderContracts() {
  const ipc = {
    $comment:
      'GENERATED by apps/desktop/src/shared/contract-json.test.ts from packages/core (zod). Do not edit; run `bun run gen:contracts`.',
    protocolVersion: PROTOCOL_VERSION,
    errorCodes: ErrorCode.options,
    envelope: schema(IpcEnvelope, 'input'),
    result: schema(IpcResult, 'output'),
    channels: Object.fromEntries(
      Object.entries(ipcContract).map(([name, d]) => [
        name,
        {
          version: d.version,
          capability: d.capability,
          request: requestSpec(d.request),
          response: schema(d.response, 'output'),
        },
      ]),
    ),
    events: Object.fromEntries(
      Object.entries(eventContract).map(([name, d]) => [
        name,
        {
          capability: d.capability,
          payload: schema(d.payload, 'output'),
          ...((d as EventDef).stream ? { stream: true } : {}),
        },
      ]),
    ),
    manifests: manifests.map((m) => ({
      id: m.id,
      capabilities: m.capabilities,
    })),
    config: {
      defaults: defaultConfig(),
      schema: schema(ConfigSchema, 'output'),
    },
  };
  const typesOf = (u: { options: readonly unknown[] }) =>
    u.options.map(
      (o) => (o as { shape: { type: { value: string } } }).shape.type.value,
    );
  const helper = {
    $comment:
      'GENERATED by apps/desktop/src/shared/contract-json.test.ts from packages/core/src/helper/protocol.ts. Do not edit; run `bun run gen:contracts`.',
    protocolVersion: HELPER_PROTOCOL_VERSION,
    helperToHostTypes: typesOf(HelperToHost),
    hostToHelperTypes: typesOf(HostToHelper),
    helperToHost: schema(HelperToHost, 'input'),
    hostToHelper: schema(HostToHelper, 'input'),
  };
  const speech = {
    $comment:
      'GENERATED by apps/desktop/src/shared/contract-json.test.ts from packages/core/src/speech/protocol.ts (ADR 0046). Do not edit; run `bun run gen:contracts`.',
    protocolVersion: SPEECH_PROTOCOL_VERSION,
    limits: SPEECH_LIMITS,
    languages: SPEECH_LANGUAGES,
    speechToHostTypes: typesOf(SpeechToHost),
    hostToSpeechTypes: typesOf(HostToSpeech),
    speechToHost: schema(SpeechToHost, 'input'),
    hostToSpeech: schema(HostToSpeech, 'input'),
  };
  const samples = {
    $comment:
      'GENERATED from packages/core/src/ipc/samples.ts. Golden request/response per channel (zod output shape) + idle answers + event payloads. Do not edit; run `bun run gen:contracts`.',
    channels: Object.fromEntries(
      Object.entries(ipcSamples).map(([name, s]) => [
        name,
        {
          request: s.request ?? null,
          response: s.response,
          ...(name in idleResponses
            ? { idle: idleResponses[name as keyof typeof idleResponses] }
            : {}),
        },
      ]),
    ),
    events: eventSamples,
  };
  return {
    'contracts/ipc-samples.json': JSON.stringify(samples, null, 2) + '\n',
    'contracts/ipc-contract.json': JSON.stringify(ipc, null, 2) + '\n',
    'contracts/helper-protocol.json': JSON.stringify(helper, null, 2) + '\n',
    'contracts/speech-protocol.json': JSON.stringify(speech, null, 2) + '\n',
  };
}

describe('generated JSON contracts (consumed by the Rust/Tauri build)', () => {
  for (const [rel, text] of Object.entries(renderContracts())) {
    it(`${rel} is up to date with the zod source`, () => {
      const file = path.join(root, rel);
      if (UPDATE) fs.writeFileSync(file, text);
      const onDisk = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
      expect(
        onDisk === text,
        `${rel} is stale: run \`bun run gen:contracts\` and commit it`,
      ).toBe(true);
    });
  }

  it('golden samples cover every channel and event and are zod-valid output', () => {
    expect(Object.keys(ipcSamples).sort()).toEqual(
      Object.keys(ipcContract).sort(),
    );
    expect(Object.keys(eventSamples).sort()).toEqual(
      Object.keys(eventContract).sort(),
    );
    for (const [name, def] of Object.entries(ipcContract)) {
      const s = ipcSamples[name as keyof typeof ipcSamples];
      const req = def.request.safeParse(s.request);
      expect(req.success, `${name} request`).toBe(true);
      const res = def.response.safeParse(s.response);
      expect(res.success, `${name} response`).toBe(true);
      // Output-shaped: parsing adds no defaults, so the Rust side can emit it verbatim.
      expect(res.data, `${name} response is not output-shaped`).toEqual(
        s.response,
      );
      if (name in idleResponses) {
        const idle = idleResponses[name as keyof typeof idleResponses];
        expect(def.response.parse(idle), `${name} idle`).toEqual(idle);
      }
    }
    for (const [name, def] of Object.entries(eventContract)) {
      const p = eventSamples[name as keyof typeof eventSamples];
      expect(def.payload.parse(p), name).toEqual(p);
    }
  });

  it('every channel and event capability is held by at least one sub app', () => {
    const held = new Set(manifests.flatMap((m) => m.capabilities));
    for (const d of [
      ...Object.values(ipcContract),
      ...Object.values(eventContract),
    ])
      expect(held.has(d.capability), d.capability).toBe(true);
  });
});
